#!/usr/bin/env python3
"""Convert the Anki tab-separated export into cards.js for the flashcard app.

Usage:  python3 build.py [deck.txt] [cards.js]
"""
import hashlib
import json
import sys

DEFAULT_IN = "CMS_Intro_Sommelier_Anki_Deck.txt"
DEFAULT_OUT = "cards.js"
TAG_PREFIX = "CMS_Intro "

# Tags whose underscore is part of the name, not a parent/child split.
DECK_NAMES = {
    "Australia_NZ": ["Australia & New Zealand"],
    "South_America": ["South America"],
    "South_Africa": ["South Africa"],
    "Beer_Sake": ["Beer & Sake"],
    "Other_Europe": ["Other Europe"],
    "USA_PacNW": ["USA", "Pacific Northwest"],
}


def card_id(question: str) -> str:
    """Stable id from the question text, so answer edits keep progress."""
    return hashlib.sha1(question.strip().encode("utf-8")).hexdigest()[:10]


def deck_path(tag: str) -> list[str]:
    """'CMS_Intro France_Bordeaux' -> ['France', 'Bordeaux']."""
    name = tag.strip()
    if name.startswith(TAG_PREFIX):
        name = name[len(TAG_PREFIX):]
    if name in DECK_NAMES:
        return list(DECK_NAMES[name])
    return name.split("_", 1) if name else ["Misc"]


def parse_deck(text: str) -> list[dict]:
    cards = []
    for line in text.splitlines():
        if not line.strip() or line.startswith("#"):
            continue
        cols = line.split("\t")
        if len(cols) < 2:
            continue
        q, a = cols[0].strip(), cols[1].strip()
        tag = cols[2] if len(cols) > 2 else ""
        cards.append({"id": card_id(q), "q": q, "a": a, "deck": deck_path(tag)})
    return cards


def main(argv: list[str]) -> int:
    src = argv[1] if len(argv) > 1 else DEFAULT_IN
    dst = argv[2] if len(argv) > 2 else DEFAULT_OUT
    with open(src, encoding="utf-8") as f:
        cards = parse_deck(f.read())
    ids = [c["id"] for c in cards]
    if len(ids) != len(set(ids)):
        print("warning: duplicate question text produces duplicate ids", file=sys.stderr)
    with open(dst, "w", encoding="utf-8") as f:
        f.write("// Generated by build.py from %s. Do not edit by hand.\n" % src)
        f.write("window.CARDS = ")
        json.dump(cards, f, ensure_ascii=False, indent=1)
        f.write(";\n")
    print(f"wrote {len(cards)} cards to {dst}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
